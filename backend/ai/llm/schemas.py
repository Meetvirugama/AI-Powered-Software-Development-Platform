"""
LLM Request, Response, and Exception Domain Schemas.

Provides typed primitives for chat messages, inference requests, structured output
specifications, and a standardized exception hierarchy across all LLM providers.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from typing import Any, Literal, TypeVar

from pydantic import BaseModel, ConfigDict, Field

T = TypeVar("T", bound=BaseModel)


# ---------------------------------------------------------------------------
# Message Primitive
# ---------------------------------------------------------------------------


class Message(BaseModel):
    """
    A single turn in an LLM conversation.

    Attributes:
        role: Message origin ('system', 'user', or 'assistant').
        content: Raw text content of the turn.
    """

    role: Literal["system", "user", "assistant"]
    content: str

    def to_dict(self) -> dict[str, str]:
        """Convert message to dictionary format required by LLM provider APIs."""
        return {"role": self.role, "content": self.content}

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> Message:
        """Construct Message from dictionary or mapping."""
        return cls(
            role=data.get("role", "user"),  # type: ignore[arg-type]
            content=str(data.get("content", "")),
        )

    @classmethod
    def from_any(cls, obj: Any) -> Message:
        """Coerce an object into a Message instance."""
        if isinstance(obj, Message):
            return obj
        if isinstance(obj, Mapping):
            return cls.from_dict(obj)
        role = getattr(obj, "role", "user")
        content = getattr(obj, "content", "")
        return cls(role=role, content=str(content))


# ---------------------------------------------------------------------------
# Request Primitive
# ---------------------------------------------------------------------------


class LLMRequest(BaseModel):
    """
    Standardized inference request passed to LLMGateway and providers.

    Attributes:
        model: Provider-specific model name (e.g. 'gpt-4o', 'openai/gpt-oss-120b').
        messages: Chronological conversation history including system prompt.
        temperature: Sampling temperature between 0.0 (deterministic) and 2.0 (creative).
        max_tokens: Maximum tokens in generated completion.
        response_schema: Optional Pydantic model for JSON-mode schema validation.
    """

    model: str = Field(..., description="Provider model identifier, e.g. 'gpt-4o'")
    messages: list[Message]
    temperature: float = Field(0.0, ge=0.0, le=2.0)
    max_tokens: int = Field(2048, ge=1)
    response_schema: type[BaseModel] | None = Field(
        default=None,
        description="Optional Pydantic schema to enforce and validate JSON output.",
        exclude=True,
    )

    model_config = ConfigDict(arbitrary_types_allowed=True)

    @classmethod
    def create(
        cls,
        model: str,
        messages: Sequence[Message | Mapping[str, Any] | Any],
        temperature: float = 0.0,
        max_tokens: int = 2048,
        response_schema: type[BaseModel] | None = None,
    ) -> LLMRequest:
        """Convenience constructor that normalizes heterogeneous message sequences."""
        norm_messages = [Message.from_any(m) for m in messages]
        return cls(
            model=model,
            messages=norm_messages,
            temperature=temperature,
            max_tokens=max_tokens,
            response_schema=response_schema,
        )


# ---------------------------------------------------------------------------
# Response Primitive
# ---------------------------------------------------------------------------


class LLMResponse(BaseModel):
    """
    Standardized, immutable completion response returned by LLMGateway.

    Attributes:
        content: Natural language or raw JSON text generated by the model.
        model: Effective model name returned by the provider.
        input_tokens: Number of prompt/input tokens consumed.
        output_tokens: Number of completion/output tokens generated.
        latency_ms: Round-trip execution time in milliseconds.
    """

    content: str
    model: str
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: float = 0.0

    model_config = ConfigDict(frozen=True)

    @property
    def total_tokens(self) -> int:
        """Total tokens (input + output) consumed by this request."""
        return self.input_tokens + self.output_tokens

    def parse_json(self) -> dict[str, Any]:
        """
        Parse response content as a JSON dictionary, stripping code fences if present.

        Raises:
            json.JSONDecodeError: If content is not valid JSON.
        """
        raw = self.content.strip()
        if raw.startswith("```"):
            lines = raw.splitlines()
            if len(lines) >= 2 and lines[0].startswith("```"):
                raw = "\n".join(lines[1:-1] if lines[-1].strip() == "```" else lines[1:])
        return json.loads(raw)

    def parse_schema(self, schema_cls: type[T]) -> T:
        """
        Validate and deserialize response JSON content into the specified Pydantic model.

        Raises:
            LLMValidationError: If parsing or schema validation fails.
        """
        try:
            data = self.parse_json()
            return schema_cls.model_validate(data)
        except Exception as exc:
            raise LLMValidationError(f"Failed to validate response against {schema_cls.__name__}: {exc}") from exc


# ---------------------------------------------------------------------------
# Exception Hierarchy
# ---------------------------------------------------------------------------


class LLMError(Exception):
    """
    Base structured exception for all LLM gateway and provider failures.

    Attributes:
        message: Human-readable error description.
        retryable: True if caller may retry (e.g. transient network or rate limit).
        provider: Name of provider that produced the error.
        status_code: Optional upstream HTTP status code.
    """

    def __init__(
        self,
        message: str,
        *,
        retryable: bool = False,
        provider: str | None = None,
        status_code: int | None = None,
    ) -> None:
        super().__init__(message)
        self.message = message
        self.retryable = retryable
        self.provider = provider
        self.status_code = status_code

    def __repr__(self) -> str:
        return (
            f"{self.__class__.__name__}(message={self.message!r}, "
            f"retryable={self.retryable}, provider={self.provider!r}, status_code={self.status_code})"
        )


class LLMTimeoutError(LLMError):
    """Raised when an LLM inference request exceeds the configured deadline."""

    def __init__(
        self,
        detail: str = "LLM request timed out.",
        *,
        provider: str | None = None,
    ) -> None:
        super().__init__(detail, retryable=True, provider=provider, status_code=504)


class LLMRateLimitError(LLMError):
    """Raised when an LLM provider enforces a rate or quota limit (HTTP 429)."""

    def __init__(
        self,
        detail: str = "LLM rate limit reached.",
        *,
        retry_after: float | None = None,
        provider: str | None = None,
    ) -> None:
        super().__init__(detail, retryable=True, provider=provider, status_code=429)
        self.retry_after = retry_after


class LLMUnavailableError(LLMError):
    """Raised when an LLM provider returns a 5xx error or transport failure."""

    def __init__(
        self,
        detail: str = "",
        *,
        status_code: int = 503,
        provider: str | None = None,
    ) -> None:
        msg = f"LLM provider unavailable. {detail}".strip() if detail else "LLM provider unavailable."
        super().__init__(msg, retryable=True, provider=provider, status_code=status_code)


class LLMAuthenticationError(LLMError):
    """Raised when provider authentication fails (HTTP 401/403)."""

    def __init__(
        self,
        detail: str = "LLM provider authentication failed.",
        *,
        status_code: int = 401,
        provider: str | None = None,
    ) -> None:
        super().__init__(detail, retryable=False, provider=provider, status_code=status_code)


class LLMValidationError(LLMError):
    """Raised when an LLM output fails JSON decoding or Pydantic schema validation."""

    def __init__(
        self,
        detail: str = "",
        *,
        provider: str | None = None,
        raw_response: str | None = None,
    ) -> None:
        self.raw_response = raw_response
        msg = (
            f"LLM response failed schema validation. {detail}".strip()
            if detail
            else "LLM response failed schema validation."
        )
        super().__init__(msg, retryable=False, provider=provider, status_code=422)
