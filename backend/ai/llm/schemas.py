"""
LLM Request, Response, and Exception Domain Schemas.

Provides typed primitives for chat messages, inference requests, structured output
specifications, and a standardized exception hierarchy across all LLM providers.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from typing import Any, Literal, TypeVar

from pydantic import BaseModel, ConfigDict, Field

T = TypeVar("T", bound=BaseModel)


# ---------------------------------------------------------------------------
# Message Primitive
# ---------------------------------------------------------------------------


class Message(BaseModel):
    """
    A single turn in an LLM conversation.

    Attributes:
        role: Message origin ('system', 'user', or 'assistant').
        content: Raw text content of the turn.
    """

    role: Literal["system", "user", "assistant"]
    content: str

    def to_dict(self) -> dict[str, str]:
        """Convert message to dictionary format required by LLM provider APIs."""
        return {"role": self.role, "content": self.content}

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> Message:
        """Construct Message from dictionary or mapping."""
        role = data.get("role", "user")
        safe_role: Literal["system", "user", "assistant"] = (
            role if role in ("system", "user", "assistant") else "user"
        )
        return cls(
            role=safe_role,
            content=str(data.get("content", "")),
        )

    @classmethod
    def from_any(cls, obj: Any) -> Message:
        """Coerce an object into a Message instance."""
        if isinstance(obj, Message):
            return obj
        if isinstance(obj, Mapping):
            return cls.from_dict(obj)
        role = getattr(obj, "role", "user")
        safe_role: Literal["system", "user", "assistant"] = (
            role if role in ("system", "user", "assistant") else "user"
        )
        content = getattr(obj, "content", "")
        return cls(role=safe_role, content=str(content))


# ---------------------------------------------------------------------------
# Request Primitive
# ---------------------------------------------------------------------------


class LLMRequest(BaseModel):
    """
    Standardized inference request passed to LLMGateway and providers.

    Attributes:
        model: Provider-specific model name (e.g. 'gpt-4o', 'openai/gpt-oss-120b').
        messages: Chronological conversation history including system prompt.
        temperature: Sampling temperature between 0.0 (deterministic) and 2.0 (creative).
        max_tokens: Maximum tokens in generated completion.
        response_schema: Optional Pydantic model for JSON-mode schema validation.
    """

    model: str = Field(..., description="Provider model identifier, e.g. 'gpt-4o'")
    messages: list[Message]
    temperature: float = Field(default=0.0, ge=0.0, le=2.0)
    max_tokens: int = Field(default=2048, ge=1)
    response_schema: type[BaseModel] | None = Field(
        default=None,
        description="Optional Pydantic schema to enforce and validate JSON output.",
        exclude=True,
    )
    response_format: dict[str, Any] | None = Field(
        default=None,
        description="Optional provider response format dictionary, e.g. {'type': 'json_object'}.",
    )
    request_id: str | None = Field(
        default=None,
        description="Optional correlation identifier for tracing.",
    )

    model_config = ConfigDict(arbitrary_types_allowed=True, extra="allow")

    @classmethod
    def create(
        cls,
        model: str,
        messages: Sequence[Message | Mapping[str, Any] | Any],
        temperature: float = 0.0,
        max_tokens: int = 2048,
        response_schema: type[BaseModel] | None = None,
        response_format: dict[str, Any] | None = None,
        request_id: str | None = None,
        **kwargs: Any,
    ) -> LLMRequest:
        """Convenience constructor that normalizes heterogeneous message sequences."""
        norm_messages = [Message.from_any(m) for m in messages]
        return cls(
            model=model,
            messages=norm_messages,
            temperature=temperature,
            max_tokens=max_tokens,
            response_schema=response_schema,
            response_format=response_format,
            request_id=request_id,
            **kwargs,
        )


