class LLMToolRequest(BaseModel):
    """
    Standardized inference request carrying available tool definitions.

    Attributes:
        model: Provider-specific model name.
        messages: Conversation history including system prompt, user questions,
                  prior assistant tool calls, and tool execution results.
        tools: List of normalized tool definitions exposed to the model.
        tool_choice: Mode ('auto', 'none', 'required', or specific tool constraint).
        temperature: Sampling temperature (default 0.0 for deterministic tool calling).
        max_tokens: Maximum tokens in generated completion.
        request_id: Optional correlation identifier for tracing.
    """

    model: str = Field(..., description="Provider model identifier, e.g. 'gemini-flash-lite-latest'")
    messages: list[Message]
    tools: list[LLMToolDefinition] = Field(default_factory=list)
    tool_choice: str | dict[str, Any] | None = Field(
        default=None,
        description="Optional tool selection directive: 'auto', 'none', 'required', or specific tool name.",
    )
    temperature: float = Field(default=0.0, ge=0.0, le=2.0)
    max_tokens: int = Field(default=1024, ge=1)
    allow_fallback: bool = Field(default=True, description="Whether fallback provider may be attempted on outage.")
    request_id: str | None = Field(
        default=None,
        description="Optional correlation identifier for tracing.",
    )
    estimated_tokens: int | None = Field(
        default=None,
        description="Optional estimated prompt tokens for calibration telemetry.",
    )
    feature: str | None = Field(
        default=None,
        description="Optional feature or workflow category for calibration telemetry.",
    )

    model_config = ConfigDict(arbitrary_types_allowed=True, extra="allow")

    @classmethod
    def create(
        cls,
        model: str,
        messages: Sequence[Message | Mapping[str, Any] | Any],
        tools: Sequence[LLMToolDefinition] | None = None,
        tool_choice: str | dict[str, Any] | None = None,
        temperature: float = 0.0,
        max_tokens: int = 1024,
        request_id: str | None = None,
        estimated_tokens: int | None = None,
        feature: str | None = None,
        **kwargs: Any,
    ) -> LLMToolRequest:
        """Convenience constructor that normalizes heterogeneous message sequences."""
        norm_messages = [Message.from_any(m) for m in messages]
        return cls(
            model=model,
            messages=norm_messages,
            tools=list(tools or []),
            tool_choice=tool_choice,
            temperature=temperature,
            max_tokens=max_tokens,
            request_id=request_id,
            estimated_tokens=estimated_tokens,
            feature=feature,
            **kwargs,
        )


class LLMToolResponse(BaseModel):
    """
    Normalized response from an LLM that supports tool calling.

    Attributes:
        content: Natural language text response (empty or explanation if tool_calls present).
        tool_calls: List of requested tool invocations emitted by the model.
        model: Effective model name returned by the provider.
        input_tokens: Prompt/input token count.
        output_tokens: Completion/output token count.
        latency_ms: Round-trip execution time in milliseconds.
        finish_reason: Provider finish reason ('stop', 'tool_calls', 'function_call', etc.).
        provider: Name of the generating provider ('gemini', 'groq').
    """

    content: str = ""
    tool_calls: list[LLMToolCall] = Field(default_factory=list)
    model: str
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: float = 0.0
    finish_reason: str | None = None
    provider: str | None = None

    model_config = ConfigDict(frozen=True)

    @property
    def is_final(self) -> bool:
        """True if the model produced a final textual answer rather than calling tools."""
        return len(self.tool_calls) == 0

    @property
    def total_tokens(self) -> int:
        """Total tokens (input + output) consumed by this request."""
        return self.input_tokens + self.output_tokens


