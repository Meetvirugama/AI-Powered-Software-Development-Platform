class ToolParameterSchema(BaseModel):
    """
    JSON schema specification for tool parameters.

    Conforms to standard JSON Schema (Draft 7 / 2020-12) as expected by
    tool-calling APIs (Gemini functionDeclarations, Groq/OpenAI function parameters).
    """

    type: str = "object"
    properties: dict[str, Any] = Field(default_factory=dict)
    required: list[str] = Field(default_factory=list)
    description: str | None = None

    model_config = ConfigDict(extra="allow")


class LLMToolDefinition(BaseModel):
    """
    Normalized definition of a tool exposed to an LLM.

    Attributes:
        name: Unique tool identifier (alphanumeric + underscores).
        description: Natural-language explanation of what the tool does.
        parameters: JSON schema dictionary describing expected arguments.
        strict: Optional flag for providers supporting strict schema adherence.
    """

    name: str = Field(..., pattern=r"^[a-zA-Z0-9_-]+$")
    description: str = Field(..., min_length=1)
    parameters: dict[str, Any] = Field(default_factory=lambda: {"type": "object", "properties": {}})
    strict: bool | None = None

    def to_gemini_dict(self) -> dict[str, Any]:
        """Convert normalized definition to Gemini FunctionDeclaration wire format."""
        return {
            "name": self.name,
            "description": self.description,
            "parameters": self.parameters,
        }

    def to_openai_dict(self) -> dict[str, Any]:
        """Convert normalized definition to OpenAI/Groq function tool wire format."""
        d: dict[str, Any] = {
            "type": "function",
            "function": {
                "name": self.name,
                "description": self.description,
                "parameters": self.parameters,
            },
        }
        if self.strict is not None:
            d["function"]["strict"] = self.strict
        return d


class LLMToolCall(BaseModel):
    """
    Normalized representation of a tool call request generated by the model.

    Attributes:
        id: Unique correlation identifier for this tool call.
        name: Name of the tool to invoke.
        arguments: Validated structured dictionary of arguments.
    """

    id: str = Field(default_factory=lambda: "")
    name: str
    arguments: dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(extra="ignore")


class LLMToolResult(BaseModel):
    """
    Normalized result of executing a tool call, ready to return to the model.

    Attributes:
        tool_call_id: Identifier matching the corresponding LLMToolCall.
        name: Name of the tool that executed.
        result: Structured output data, dictionary, or string representation.
        is_error: Whether execution resulted in a trapped failure.
        error_message: Optional human-readable error description.
    """

    tool_call_id: str
    name: str
    result: Any = None
    is_error: bool = False
    error_message: str | None = None

    def to_content_str(self) -> str:
        """Serialize result payload to a safe JSON or string representation."""
        if self.is_error:
            return json.dumps({"error": self.error_message or "Tool execution error", "is_error": True})
        if isinstance(self.result, str):
            return self.result
        try:
            return json.dumps(self.result, default=str)
        except (TypeError, ValueError):
            return str(self.result)


