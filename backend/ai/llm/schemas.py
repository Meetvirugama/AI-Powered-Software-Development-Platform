class LLMResponse(BaseModel):
    """
    Standardized, immutable completion response returned by LLMGateway.

    Attributes:
        content: Natural language or raw JSON text generated by the model.
        model: Effective model name returned by the provider.
        input_tokens: Number of prompt/input tokens consumed.
        output_tokens: Number of completion/output tokens generated.
        latency_ms: Round-trip execution time in milliseconds.
    """

    content: str
    model: str
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: float = 0.0

    model_config = ConfigDict(frozen=True)

    @property
    def total_tokens(self) -> int:
        """Total tokens (input + output) consumed by this request."""
        return self.input_tokens + self.output_tokens

    def parse_json(self) -> Any:
        """
        Parse response content as a JSON dictionary or list, stripping code fences if present.

        Raises:
            json.JSONDecodeError: If content is not valid JSON.
        """
        raw = extract_json_payload(self.content)
        return json.loads(raw)

    def parse_schema(self, schema_cls: type[T]) -> T:
        """
        Validate and deserialize response JSON content into the specified Pydantic model.

        Raises:
            LLMValidationError: If parsing or schema validation fails.
        """
        return validate_structured_payload(self.content, schema_cls, provider=None)


# ---------------------------------------------------------------------------
# Structured Output & JSON Utilities
# ---------------------------------------------------------------------------


def extract_json_payload(content: str) -> str:
    """Extract raw JSON substring from content, stripping markdown fences and commentary."""
    raw = content.strip()
    if raw.startswith("```"):
        lines = raw.splitlines()
        if len(lines) >= 2 and lines[0].startswith("```"):
            raw = "\n".join(lines[1:-1] if lines[-1].strip() == "```" else lines[1:]).strip()

    first_brace = raw.find("{")
    first_bracket = raw.find("[")
    if (
        first_bracket != -1
        and (first_brace == -1 or first_bracket < first_brace)
        and "]" in raw
    ):
        return raw[first_bracket : raw.rfind("]") + 1]
    if first_brace != -1 and "}" in raw:
        return raw[first_brace : raw.rfind("}") + 1]
    return raw


def validate_structured_payload(
    content: str,
    schema: type[BaseModel],
    provider: str | None = None,
) -> Any:
    """Validate and deserialize raw text against a Pydantic schema."""
    raw = extract_json_payload(content)
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise LLMValidationError(
            f"Response is not valid JSON: {exc}",
            provider=provider,
            raw_response=content,
        ) from exc

    if (
        isinstance(parsed, list)
        and hasattr(schema, "model_fields")
        and "findings" in getattr(schema, "model_fields", {})
    ):
        parsed = {"findings": parsed}

    try:
        return schema.model_validate(parsed)
    except Exception as exc:
        raise LLMValidationError(
            f"Schema validation failed: {exc}",
            provider=provider,
            raw_response=content,
        ) from exc


# ---------------------------------------------------------------------------
# Exception Hierarchy
# ---------------------------------------------------------------------------


class LLMError(Exception):
    """
    Base structured exception for all LLM gateway and provider failures.

    Attributes:
        message: Human-readable error description.
        retryable: True if caller may retry (e.g. transient network or rate limit).
        provider: Name of provider that produced the error.
        status_code: Optional upstream HTTP status code.
    """

    def __init__(
        self,
        message: str,
        *,
        retryable: bool = False,
        provider: str | None = None,
        status_code: int | None = None,
    ) -> None:
        super().__init__(message)
        self.message = message
        self.retryable = retryable
        self.provider = provider
        self.status_code = status_code

    def __repr__(self) -> str:
        return (
            f"{self.__class__.__name__}(message={self.message!r}, "
            f"retryable={self.retryable}, provider={self.provider!r}, status_code={self.status_code})"
        )


class LLMTimeoutError(LLMError):
    """Raised when an LLM inference request exceeds the configured deadline."""

    def __init__(
        self,
        detail: str = "LLM request timed out.",
        *,
        provider: str | None = None,
    ) -> None:
        super().__init__(detail, retryable=True, provider=provider, status_code=504)


class LLMRateLimitError(LLMError):
    """Raised when an LLM provider enforces a rate or quota limit (HTTP 429)."""

    def __init__(
        self,
        detail: str = "LLM rate limit reached.",
        *,
        retry_after: float | None = None,
        provider: str | None = None,
    ) -> None:
        super().__init__(detail, retryable=True, provider=provider, status_code=429)
        self.retry_after = retry_after


class LLMUnavailableError(LLMError):
    """Raised when an LLM provider returns a 5xx error or transport failure."""

    def __init__(
        self,
        detail: str = "",
        *,
        status_code: int = 503,
        provider: str | None = None,
    ) -> None:
        msg = f"LLM provider unavailable. {detail}".strip() if detail else "LLM provider unavailable."
        super().__init__(msg, retryable=True, provider=provider, status_code=status_code)


class LLMAuthenticationError(LLMError):
    """Raised when provider authentication fails (HTTP 401/403)."""

    def __init__(
        self,
        detail: str = "LLM provider authentication failed.",
        *,
        status_code: int = 401,
        provider: str | None = None,
    ) -> None:
        super().__init__(detail, retryable=False, provider=provider, status_code=status_code)


class LLMValidationError(LLMError):
    """Raised when an LLM output fails JSON decoding or Pydantic schema validation."""

    def __init__(
        self,
        detail: str = "",
        *,
        provider: str | None = None,
        raw_response: str | None = None,
    ) -> None:
        self.raw_response = raw_response
        msg = (
            f"LLM response failed schema validation. {detail}".strip()
            if detail
            else "LLM response failed schema validation."
        )
        super().__init__(msg, retryable=False, provider=provider, status_code=422)


