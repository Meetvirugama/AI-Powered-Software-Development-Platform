class Message(BaseModel):
    """
    A single turn in an LLM conversation.

    Attributes:
        role: Message origin ('system', 'user', 'assistant', or 'tool').
        content: Raw text content of the turn.
        tool_calls: Optional list of tool calls requested by assistant.
        tool_call_id: Correlation ID for tool result turns.
        name: Function or tool name for tool result turns.
    """

    role: Literal["system", "user", "assistant", "tool"]
    content: str = ""
    tool_calls: list[LLMToolCall] | None = None
    tool_call_id: str | None = None
    name: str | None = None

    def to_dict(self) -> dict[str, Any]:
        """Convert message to dictionary format required by LLM provider APIs."""
        d: dict[str, Any] = {"role": self.role, "content": self.content}
        if self.tool_calls is not None:
            d["tool_calls"] = [tc.model_dump() for tc in self.tool_calls]
        if self.tool_call_id is not None:
            d["tool_call_id"] = self.tool_call_id
        if self.name is not None:
            d["name"] = self.name
        return d

    @classmethod
    def system(cls, content: str) -> Message:
        """Create a system instruction turn."""
        return cls(role="system", content=content)

    @classmethod
    def user(cls, content: str) -> Message:
        """Create a user query turn."""
        return cls(role="user", content=content)

    @classmethod
    def assistant(cls, content: str = "", tool_calls: list[LLMToolCall] | None = None) -> Message:
        """Create an assistant response turn, optionally carrying tool calls."""
        return cls(role="assistant", content=content, tool_calls=tool_calls)

    @classmethod
    def tool_result(cls, tool_call_id: str, name: str, content: str) -> Message:
        """Create a tool execution result turn."""
        return cls(role="tool", tool_call_id=tool_call_id, name=name, content=content)

    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> Message:
        """Construct Message from dictionary or mapping."""
        role = data.get("role", "user")
        safe_role: Literal["system", "user", "assistant", "tool"] = (
            role if role in ("system", "user", "assistant", "tool") else "user"
        )
        tool_calls_raw = data.get("tool_calls")
        tool_calls = None
        if tool_calls_raw:
            tool_calls = [
                tc if isinstance(tc, LLMToolCall) else LLMToolCall.model_validate(tc)
                for tc in tool_calls_raw
            ]
        return cls(
            role=safe_role,
            content=str(data.get("content", "") or ""),
            tool_calls=tool_calls,
            tool_call_id=data.get("tool_call_id"),
            name=data.get("name"),
        )

    @classmethod
    def from_any(cls, obj: Any) -> Message:
        """Coerce an object into a Message instance."""
        if isinstance(obj, Message):
            return obj
        if isinstance(obj, Mapping):
            return cls.from_dict(obj)
        role = getattr(obj, "role", "user")
        safe_role: Literal["system", "user", "assistant", "tool"] = (
            role if role in ("system", "user", "assistant", "tool") else "user"
        )
        content = getattr(obj, "content", "")
        tool_calls = getattr(obj, "tool_calls", None)
        tool_call_id = getattr(obj, "tool_call_id", None)
        name = getattr(obj, "name", None)
        return cls(
            role=safe_role,
            content=str(content or ""),
            tool_calls=tool_calls,
            tool_call_id=tool_call_id,
            name=name,
        )


